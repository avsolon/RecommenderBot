from telegram import Update
from telegram.ext import CallbackContext


def help_handler(update: Update, context: CallbackContext):
    text = """
🤖 *Мой Рекомендатор* — твой личный помощник по хранению и поиску рекомендаций!

📌 *Основные команды:*

➕ *Добавить* — создать новую рекомендацию
🔍 *Найти* — поиск по категории и ключевым словам
🎲 *Случайная* — случайная рекомендация из твоих
📋 *Список* — все твои рекомендации
✏️ *Редактировать* — изменить запись
🗑 *Удалить* — удалить запись

👥 *Социальные функции:*
🌍 *Общие* — смотреть публичные рекомендации других
🏆 *Топ* — самые популярные рекомендации

📱 *Команды:*
/add — добавить
/find — найти
/random — случайная
/list — список
/edit — редактировать
/del — удалить
/public — общие рекомендации
/top — топ рекомендаций

💡 *Совет:* Делись своими рекомендациями с другими, делая их публичными при добавлении!
    """
    update.message.reply_text(text, parse_mode="Markdown")
